import { chromium } from '@playwright/test'
const b = await chromium.launch()
const c = await b.newContext({ viewport:{width:1366,height:800} })
const p = await c.newPage()
const msgs=[]
p.on('console', m=>msgs.push(m.type()+': '+m.text())); p.on('pageerror', e=>msgs.push('pageerror '+e.message))
await p.addInitScript(()=>document.addEventListener('securitypolicyviolation',e=>console.log('CSPV '+e.violatedDirective+' '+e.blockedURI)))
await p.route(/fonts\.googleapis\.com/, r=>r.fulfill({contentType:'text/css',body:"@font-face{font-family:'X';src:url(https://fonts.gstatic.com/x.woff2)}"}))
await p.route(/fonts\.gstatic\.com/, r=>r.fulfill({contentType:'font/woff2',body:''}))
await p.route(/cdn\.simpleicons\.org/, r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>'}))
await p.goto('http://localhost:4180/'); await p.waitForTimeout(500)
await p.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=400){scrollTo(0,y);await new Promise(r=>setTimeout(r,80))}})
await p.click('.theme-btn'); await p.waitForTimeout(500)
console.log('imgs', await p.evaluate(()=>[...document.querySelectorAll('.skill-chip img')].filter(i=>i.complete&&i.naturalWidth>0).length), 'sections', await p.locator('[data-section]:not([data-section-placeholder])').count())
console.log(msgs.length?msgs.join('\n'):'no console messages / CSP violations')
await b.close()
